type Range = [number, number];
type Rating = 0 | 1 | 2;

export interface StudyCountry {
  id: string;
  name: string;
  flagCode: string;
  region: StudyRegion;
  /** One of the six destinations with a full guide page on the site. */
  popular?: boolean;
  /** True for the regional fallbacks used when a student picks "somewhere else". */
  generic?: boolean;
  currency: string;
  tuition: { undergraduate: Range; masters: Range; phd: Range; premium: Range };
  /** What most students actually pay, where that sits well below the middle of the range (e.g. near-free public universities). */
  typicalTuition?: Partial<Record<"undergraduate" | "masters", number>>;
  tuitionNote: string;
  living: { rent: number; food: number; transport: number; personal: number };
  bigCities: string;
  bigCityFactor: number;
  healthPerYear: number;
  healthNote: string;
  /** Health cover charged for the whole course before the visa is issued (e.g. UK IHS). */
  healthUpfront?: boolean;
  applicationFee: number;
  flightNgn: number;
  settlingInNgn: number;
  years: { undergraduate: number; masters: number; phd: number; medicine: number };
  intakes: Month[];
  /** How many months before the intake applications should normally be submitted. */
  applyMonthsAhead: number;
  deadlineNote?: string;
  language: "english" | "mixed" | "local-first";
  languageNote: string;
  ieltsMin: number;
  englishNote: string;
  /** Many universities accept a WAEC/NECO English credit instead of IELTS. */
  waecEnglishOften?: boolean;
  minGradePercent: number;
  /** Whether WAEC/NECO results alone usually give direct entry to a Bachelor's. */
  waecDirectEntry: "yes" | "sometimes" | "rarely";
  workHours: number;
  workNote: string;
  pswMonths: number;
  pswNote: string;
  visa: {
    name: string;
    fee: number;
    weeks: Range;
    /** Typical extra wait for an appointment in Lagos/Abuja, in weeks. */
    appointmentWaitWeeks: number;
    confirmationDoc: string;
    funds: string;
    medical?: string;
    arrival: string;
  };
  ratings: { ranking: Rating; scholarships: Rating; settlement: Rating; community: Rating };
  scholarshipNote: string;
  strongFields: FieldId[];
  watchOut?: string;
}

